"""The Home screen (Locks 07, 08, 14 and 18): the business at a glance for one person.

Headline figures for the areas this person covers, what needs attention, decisions waiting, good news, what the
AI team finished today, and anything wrong with the team or the data. Everything is read from verified state;
nothing here is generated by a model."""
import re
from datetime import datetime, timedelta
from zoneinfo import ZoneInfo

from sqlalchemy import or_, select
from sqlalchemy.orm import Session

from . import data, health, tools
from .db import utcnow
from .metrics import MetricEngine
from .models import Approval, WorkItem
from .tenancy import TenantConfig

URGENT = ("CRITICAL", "HIGH")
OPEN = ("QUEUED", "RUNNING", "INVESTIGATING", "VALIDATING", "NEEDS_RETRY", "NEEDS_HUMAN_REVIEW", "WAITING_FOR_DATA")


def _brief(w: WorkItem, cfg: TenantConfig | None = None) -> dict:
    f = w.finding or {}
    out = {"id": w.id, "title": w.title, "employee": w.employee, "priority": w.priority, "status": w.status, "type": w.type,
           "headline": f.get("headline"), "quality": f.get("evidence_quality"), "outcome": w.outcome,
           "updated_at": w.updated_at.isoformat() + "Z"}
    if cfg is not None:
        emp = cfg.employees.get(w.employee)
        area = cfg.layout.areas.get(emp.area) if emp else None
        out["area"] = area.name if area else None
        out.update(subject_of(w))
        out["key_figure"] = key_figure(cfg, w)
    return out


def subject_of(w: WorkItem) -> dict:
    """What an alert is about, as the business names it: the SKU, order, line or invoice, and who it concerns."""
    ctx = w.context or {}
    groups = [g for g in (ctx.get("groups") or [ctx.get("group")]) if g is not None]
    check = ctx.get("check") or {}
    return {"code": str(check.get("invoice") or groups[0]) if (check or groups) else None,
            "party": check.get("supplier"), "more": max(0, len(groups) - 1)}


_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


def key_figure(cfg: TenantConfig, w: WorkItem) -> dict | None:
    """The one verified number that made the alert fire (never an AI figure): the rule's own metric for the first item it
    covers, or the billed amount for an invoice check. None when the task has no such number."""
    ctx = w.context or {}
    check = ctx.get("check") or {}
    if check.get("kind") == "duplicate_invoice" and check.get("amount") is not None:
        return {"value": check["amount"], "unit": cfg.currency, "label": "invoice value"}
    if check.get("kind") == "three_way_match":
        q, p = check.get("billed_quantity"), check.get("billed_unit_price")
        if q is not None and p is not None:
            return {"value": round(q * p, 2), "unit": cfg.currency, "label": "billed", "quantity": q, "unit_price": p}
        return None
    pack = ctx.get("evidence_pack")
    if pack is None and ctx.get("groups"):
        pack = (ctx.get("evidence_packs") or {}).get(str(ctx["groups"][0]))
    rule = next((r for r in cfg.rules if r.id == w.rule_id), None)
    if not pack or rule is None or not rule.when:
        return None
    for name in _NAME.findall(rule.when):  # in the order the rule names them: the first is what it is about
        m = pack.get(name)
        if isinstance(m, dict) and m.get("value") is not None:
            return {"value": m["value"], "unit": m.get("unit"), "label": m.get("label")}
    return None


def kpis(db: Session, cfg: TenantConfig, areas: set[str] | None) -> list[dict]:
    """areas=None means every area (owners)."""
    engine = MetricEngine(db, cfg)
    out = []
    for k in cfg.home.kpis:
        if areas is not None and k.area not in areas:
            continue
        m = cfg.metrics[k.metric]
        value = engine.for_group(k.metric, None, None)
        previous = engine.for_group(k.compare, None, None) if k.compare else None
        change = None
        if value is not None and previous not in (None, 0):
            change = (value - previous) / abs(previous)
        trend = None if change is None or abs(change) < 0.005 else ("up" if change > 0 else "down")
        states = [data.freshness(db, cfg, d)[0] for d in tools._metric_datasets(cfg, [k.metric])]
        out.append({"metric": k.metric, "label": k.label or m.label, "unit": m.unit, "area": k.area, "value": value,
                    "previous": previous, "change": round(change, 4) if change is not None else None, "trend": trend,
                    "good": None if trend is None else trend == k.good,
                    "freshness": "STALE" if "STALE" in states else ("NEVER_SYNCED" if "NEVER_SYNCED" in states else "CURRENT")})
    return out


def approval_visible(cfg: TenantConfig, ap, employees: set[str], areas: set[str] | None) -> bool:
    """A decision is visible to whoever covers the proposing employee or the area the action belongs to, so the manager
    allowed to approve a purchase request sees it wherever it was proposed. One rule for every screen."""
    if areas is None or ap.employee in employees:
        return True
    act = cfg.actions.get(ap.action)
    return act is not None and act.area in areas


def home(db: Session, cfg: TenantConfig, employees: set[str], areas: set[str] | None) -> dict:
    now = utcnow()
    tz = ZoneInfo(cfg.timezone)
    local_midnight = datetime.now(tz).replace(hour=0, minute=0, second=0, microsecond=0)
    today_start = local_midnight.astimezone(ZoneInfo("UTC")).replace(tzinfo=None)
    items = db.execute(select(WorkItem).where(WorkItem.tenant_id == cfg.id, WorkItem.parent_id.is_(None),
                                              WorkItem.employee.in_(employees),
                                              WorkItem.updated_at >= now - timedelta(days=7))).scalars().all()
    pending = [a for a in db.execute(select(Approval).where(Approval.tenant_id == cfg.id, Approval.status == "PENDING")).scalars()
               if approval_visible(cfg, a, employees, areas)]
    waiting_ids = {a.work_id for a in pending}

    def problem(w):
        return (w.context or {}).get("sentiment") != "opportunity"

    attention = [w for w in items if problem(w) and w.finding and w.id not in waiting_ids
                 and (w.finding.get("outcome") in ("FINDING", "DATA_CONFLICT", "DATA_STALE"))
                 and (w.priority in URGENT or w.status == "NEEDS_HUMAN_REVIEW")
                 and (w.status == "NEEDS_HUMAN_REVIEW" or w.updated_at >= now - timedelta(hours=48))]
    good = [w for w in items if not problem(w) and w.finding and w.finding.get("outcome") == "FINDING"]
    done_today = [w for w in items if w.status == "COMPLETED" and w.completed_at and w.completed_at >= today_start]
    working = [w for w in items if w.status in OPEN and w.status != "NEEDS_HUMAN_REVIEW"]
    team = health.employee_health(db, cfg, employees)
    stale = []
    for sid, src in cfg.sources.items():
        states = {data.freshness(db, cfg, d)[0] for d, ds in cfg.datasets.items() if ds.source == sid}
        if states - {"CURRENT"}:
            stale.append({"id": sid, "label": src.label or sid})
    rank = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3}
    attention.sort(key=lambda w: (rank.get(w.priority, 4), -w.updated_at.timestamp()))
    return {
        "date": datetime.now(tz).strftime("%A %d %B"),
        "kpis": kpis(db, cfg, areas),
        "attention": [_brief(w, cfg) for w in attention[:8]],
        "attention_total": len(attention),
        "decisions": [{"id": a.id, "work_id": a.work_id, "title": a.title, "amount": a.amount, "employee": a.employee} for a in pending[:8]],
        "decisions_total": len(pending),
        "good_news": [_brief(w, cfg) for w in sorted(good, key=lambda w: w.updated_at, reverse=True)[:5]],
        "done_today": [_brief(w, cfg) for w in sorted(done_today, key=lambda w: w.completed_at, reverse=True)[:8]],
        "done_today_total": len(done_today),
        "in_progress": len(working),
        "team": {"total": len(team), "problems": [{"employee": e, "status": h["status"], "reasons": h["reasons"]}
                                                  for e, h in team.items() if h["status"] != "HEALTHY"]},
        "stale_sources": stale,
    }


def work_board(db: Session, cfg: TenantConfig, employees: set[str], view: str, employee: str | None = None,
               search: str = "", limit: int = 100, asked_by: int | None = None) -> dict:
    """The Work screen: the queue (everything not finished) or finished investigations, with counts. A person always sees
    the questions they asked themselves."""
    now = utcnow()
    mine = WorkItem.employee.in_(employees) if asked_by is None else or_(WorkItem.employee.in_(employees), WorkItem.created_by == asked_by)
    base = select(WorkItem).where(WorkItem.tenant_id == cfg.id, WorkItem.parent_id.is_(None), mine)
    if employee:
        base = base.where(WorkItem.employee == employee)
    open_items = db.execute(base.where(WorkItem.status.in_(OPEN))).scalars().all()
    failed_recent = db.execute(base.where(WorkItem.status == "FAILED", WorkItem.completed_at >= now - timedelta(days=7))).scalars().all()
    counts = {
        "waiting_to_start": len([w for w in open_items if w.status == "QUEUED"]),
        "working": len([w for w in open_items if w.status in ("RUNNING", "INVESTIGATING", "VALIDATING", "WAITING_FOR_DATA")]),
        "waiting_for_you": len([w for w in open_items if w.status == "NEEDS_HUMAN_REVIEW"]),
        "retrying": len([w for w in open_items if w.status == "NEEDS_RETRY"]),
        "failed_7d": len(failed_recent),
    }
    if view == "queue":
        rank = {"NEEDS_HUMAN_REVIEW": 0, "INVESTIGATING": 1, "RUNNING": 1, "VALIDATING": 1, "NEEDS_RETRY": 2, "QUEUED": 3}
        prio = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3}
        rows = sorted(open_items + failed_recent, key=lambda w: (rank.get(w.status, 4), prio.get(w.priority, 4), w.created_at))
    else:
        q = base.where(WorkItem.status == "COMPLETED").order_by(WorkItem.completed_at.desc()).limit(500)
        rows = [w for w in db.execute(q).scalars() if w.finding]
    s = search.strip().lower()
    if s:
        rows = [w for w in rows if s in w.title.lower() or s in ((w.finding or {}).get("headline") or "").lower()
                or s in (w.subject or "").lower()]
    return {"counts": counts, "total": len(rows),
            "items": [{**_brief(w, cfg), "created_at": w.created_at.isoformat() + "Z", "next": w.next_step,
                       "completed_at": w.completed_at.isoformat() + "Z" if w.completed_at else None,
                       "age_hours": round((now - w.created_at).total_seconds() / 3600, 1),
                       "good_news": (w.context or {}).get("sentiment") == "opportunity",
                       "question": (w.context or {}).get("question")} for w in rows[:limit]]}
